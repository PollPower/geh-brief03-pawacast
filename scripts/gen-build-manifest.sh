#!/bin/bash
# Generate a frozen listing of zk/build/ (file path, size, sha256) for
# repository-side auditability without checking in the large proving key.
# Run after: compactc zk/record.compact zk/build/
set -euo pipefail

cd "$(dirname "$0")/.."
if [ ! -d zk/build ]; then
  echo "zk/build/ not found. Compile first:" >&2
  echo "  compactc zk/record.compact zk/build/" >&2
  exit 1
fi

OUT="$(pwd)/zk/build-manifest.txt"
{
  echo "# zk/build/ manifest — generated by scripts/gen-build-manifest.sh"
  echo "# compactc  --version:         $(compactc --version 2>/dev/null || echo 'compactc not on PATH')"
  echo "# compactc  --language-version: $(compactc --language-version 2>/dev/null || echo '?')"
  echo "# compactc  --runtime-version:  $(compactc --runtime-version 2>/dev/null || echo '?')"
  echo "# generated at:                 $(date -u +%Y-%m-%dT%H:%M:%SZ) UTC"
  echo "#"
  echo "# <size-bytes>  <sha256>  <path>"
  (
    cd zk/build
    find . -type f -not -name '.*' | sort | while read -r f; do
      size=$(stat -c '%s' "$f")
      sha=$(sha256sum "$f" | cut -d' ' -f1)
      printf "%10d  %s  %s\n" "$size" "$sha" "${f#./}"
    done
  )
} > "$OUT"

echo "Wrote $OUT"
wc -l "$OUT"
